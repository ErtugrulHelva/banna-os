/// ASCII dışında desteklenen karakterler; konsol hücresinde `0x80 + sıra` olarak saklanır.
const EXTENDED: [char; 13] = [
    'ç', 'Ç', 'ş', 'Ş', 'ğ', 'Ğ', 'ı', 'İ', 'ö', 'Ö', 'ü', 'Ü', 'é',
];

const CEDILLA: [(usize, u8); 3] = [(12, 0x10), (13, 0x08), (14, 0x30)];

const fn with(base: u8, marks: &[(usize, u8)], clear: Option<usize>) -> [u8; 16] {
    let mut g = GLYPHS[base as usize];
    if let Some(row) = clear {
        g[row] = 0;
    }
    let mut i = 0;
    while i < marks.len() {
        g[marks[i].0] |= marks[i].1;
        i += 1;
    }
    g
}

static EXTENDED_GLYPHS: [[u8; 16]; 13] = [
    with(b'c', &CEDILLA, None),
    with(b'C', &CEDILLA, None),
    with(b's', &CEDILLA, None),
    with(b'S', &CEDILLA, None),
    with(b'g', &[(2, 0x42), (3, 0x3c)], None),
    with(b'G', &[(0, 0x42), (1, 0x3c)], None),
    with(b'i', &[], Some(3)),
    with(b'I', &[(1, 0x18)], None),
    with(b'o', &[(3, 0x24)], None),
    with(b'O', &[(1, 0x24)], None),
    with(b'u', &[(3, 0x24)], None),
    with(b'U', &[(1, 0x24)], None),
    with(b'e', &[(2, 0x08), (3, 0x10)], None),
];

/// Karakteri konsol hücresi baytına çevirir; desteklenmeyenler `?` olur.
pub fn encode(ch: char) -> u8 {
    if ch.is_ascii() {
        return ch as u8;
    }
    EXTENDED
        .iter()
        .position(|&c| c == ch)
        .map_or(b'?', |i| 0x80 + i as u8)
}

/// Hücre baytından karaktere (terminalde kopyalama için; çekirdek kullanmaz).
#[allow(dead_code)]
pub fn decode(byte: u8) -> char {
    match byte {
        0..0x80 => byte as char,
        _ => EXTENDED.get((byte - 0x80) as usize).copied().unwrap_or('?'),
    }
}

pub fn glyph(byte: u8) -> &'static [u8; 16] {
    match byte {
        0..0x80 => &GLYPHS[byte as usize],
        _ => EXTENDED_GLYPHS
            .get((byte - 0x80) as usize)
            .unwrap_or(&GLYPHS[b'?' as usize]),
    }
}
